"""### 2. Dataset Simulation & Splitting
To fully demonstrate the workflow (including class distribution, validation splits, and leakage prevention), we will generate an expanded dataset from these images, assigning them mock labels (`benign` and `malignant`) and patient IDs to prevent data leakage.
"""

import numpy as np
import pandas as pd
from sklearn.model_selection import GroupShuffleSplit

# Let's define metadata with Patient IDs to simulate preventing patient/lesion-level data leakage
# We will generate 100 sample metadata records referencing our 3 base files
np.random.seed(42)
num_samples = 150

data_records = []
for i in range(num_samples):
    # Simulate 20 unique patient IDs
    patient_id = f"PAT_{np.random.randint(1, 21):02d}"
    # Randomly assign a base image reference
    base_img = np.random.choice(image_files)
    # Assign a binary label based on patient (to create a consistent relationship and test grouping)
    label = 'malignant' if int(patient_id.split('_')[1]) % 2 == 0 else 'benign'
    data_records.append({
        'sample_id': f"SMP_{i:03d}",
        'patient_id': patient_id,
        'base_image': base_img,
        'label': label
    })

df = pd.DataFrame(data_records)
print("Dataset shape:", df.shape)
print("Class Distribution:\n", df['label'].value_counts())
print("\nUnique Patients:", df['patient_id'].nunique())
print("\nSample records:\n", df.head())

# Perform patient-level train (70%) / validation (15%) / test (15%) split using GroupShuffleSplit
gss_train = GroupShuffleSplit(n_splits=1, train_size=0.7, random_state=42)
train_idx, temp_idx = next(gss_train.split(df, groups=df['patient_id']))

df_train = df.iloc[train_idx].copy()
df_temp = df.iloc[temp_idx].copy()

# Split the remaining 30% group-wise into 50/50 validation and test (which gives 15% each of the total)
gss_val = GroupShuffleSplit(n_splits=1, train_size=0.5, random_state=42)
val_idx, test_idx = next(gss_val.split(df_temp, groups=df_temp['patient_id']))

df_val = df_temp.iloc[val_idx].copy()
df_test = df_temp.iloc[test_idx].copy()

print(f"Train size: {len(df_train)} (Patients: {df_train['patient_id'].nunique()})")
print(f"Val size: {len(df_val)} (Patients: {df_val['patient_id'].nunique()})")
print(f"Test size: {len(df_test)} (Patients: {df_test['patient_id'].nunique()})")

# Verify no leakage: set of patients in train, val, and test should be completely disjoint
assert len(set(df_train['patient_id']).intersection(set(df_val['patient_id']))) == 0, "Leakage detected!"
assert len(set(df_train['patient_id']).intersection(set(df_test['patient_id']))) == 0, "Leakage detected!"
print("Patient/lesion level leakage prevention verified successfully!")

"""### 3. Preprocessing and Augmentation
We will build a preprocessing pipeline using TensorFlow/Keras to load, resize to (224, 224), convert to RGB, normalize, and apply random data augmentation steps.
"""

import tensorflow as tf
from tensorflow.keras import layers, models

# Configure model hyper-parameters
IMG_SIZE = (224, 224)
BATCH_SIZE = 16

# Definition of the standard preprocessing + augmentation layers
data_augmentation = tf.keras.Sequential([
    layers.RandomFlip("horizontal_and_vertical"),
    layers.RandomRotation(0.2),
    layers.RandomZoom(0.1),
])

def load_and_preprocess(row):
    # Load physical image from base image path
    img_raw = tf.io.read_file(row['base_image'])
    img = tf.image.decode_jpeg(img_raw, channels=3)
    img = tf.image.resize(img, IMG_SIZE)
    # Normalization
    img = img / 255.0
    label = 1 if row['label'] == 'malignant' else 0
    return img, label

# Define generator to parse DataFrame with Dataset API
def create_dataset(dataframe, augment=False):
    ds = tf.data.Dataset.from_tensor_slices(dict(dataframe))
    ds = ds.map(lambda r: load_and_preprocess(r), num_parallel_calls=tf.data.AUTOTUNE)
    if augment:
        ds = ds.map(lambda x, y: (data_augmentation(x, training=True), y), num_parallel_calls=tf.data.AUTOTUNE)
    ds = ds.batch(BATCH_SIZE).prefetch(buffer_size=tf.data.AUTOTUNE)
    return ds

train_ds = create_dataset(df_train, augment=True)
val_ds = create_dataset(df_val, augment=False)
test_ds = create_dataset(df_test, augment=False)

"""### 4. CNN Model Architecture, Training and Callbacks
We design a custom Convolutional Neural Network (CNN) containing standard layers: Conv2D, Activation (ReLU), MaxPooling2D, Dropout, Dense, and output activation. We train using Adam and binary cross-entropy with early stopping.
"""

from tensorflow.keras.callbacks import EarlyStopping, ModelCheckpoint

# Define custom CNN model
model = models.Sequential([
    layers.Input(shape=(224, 224, 3)),

    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5),
    layers.Dense(1, activation='sigmoid')
])

model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

model.summary()

# Callbacks
callbacks = [
    EarlyStopping(monitor='val_loss', patience=5, restore_best_weights=True, verbose=1),
    ModelCheckpoint('skin_cancer_model.keras', monitor='val_loss', save_best_only=True, verbose=1)
]

# Fit the model
history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=15,
    callbacks=callbacks
)

"""### 5. Evaluation and Visualizations
We will evaluate the trained model on test data, generate performance metrics (accuracy, precision, recall, F1, confusion matrix), and plot training/validation accuracy and loss.
"""

