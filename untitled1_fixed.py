"""### 6. Interactive Prediction
This code block allows simulating prediction on a new uploaded image file with class probabilities.
"""

def predict_image(image_path):
    # Helper to predict single image file
    img = Image.open(image_path).convert('RGB')
    img_resized = img.resize((224, 224))
    img_arr = np.array(img_resized) / 255.0
    img_arr = np.expand_dims(img_arr, axis=0)

    prob = model.predict(img_arr, verbose=0)[0][0]
    label = 'malignant' if prob > 0.5 else 'benign'
    confidence = prob if label == 'malignant' else 1.0 - prob

    print(f"Predicted Class: {label} (Confidence: {confidence:.2%})")
    return label, confidence

# Test on one of our base images
